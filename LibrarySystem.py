    def create_all_tables(self):
        """Creates the 'members', 'books', and 'borrower_books' tables if they don't exist."""
        conn = self.Connect()
        if conn:
            my_cursor = conn.cursor()
            try:
                # Create members table
                my_cursor.execute("""
                    CREATE TABLE IF NOT EXISTS members (
                        PRN_NO INT AUTO_INCREMENT PRIMARY KEY,
                        Member VARCHAR(255),
                        ID VARCHAR(255) UNIQUE,
                        FirstName VARCHAR(255),
                        LastNme VARCHAR(255),
                        Address1 VARCHAR(255),
                        Mobile VARCHAR(20)
                    )
                """)
                # Create books table
                my_cursor.execute("""
                    CREATE TABLE IF NOT EXISTS books (
                        book_id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
                        book_title VARCHAR(255) NOT NULL,
                        auther_name VARCHAR(255),
                        quantity INT NOT NULL DEFAULT 0
                    )
                """)
                # Create borrower_books table with foreign keys
                my_cursor.execute("""
                    CREATE TABLE IF NOT EXISTS borrower_books (
                        borrow_id INT AUTO_INCREMENT PRIMARY KEY,
                        prn_no INT,
                        book_id INT,
                        date_borrowed DATE,
                        date_due DATE,
                        days_on_book INT,
                        late_return_fine DECIMAL(10, 2),
                        return_date DATE NULL,
                        status VARCHAR(50) DEFAULT 'borrowed',
                        FOREIGN KEY (prn_no) REFERENCES members(PRN_NO) ON DELETE CASCADE,
                        FOREIGN KEY (book_id) REFERENCES books(book_id) ON DELETE RESTRICT
                    )
                """)
                conn.commit()
                messagebox.showinfo("Database Setup", "All necessary tables (members, books, borrower_books) are ensured to exist.")
            except mysql.connector.Error as err:
                messagebox.showerror("Table Creation Error", f"Error creating tables: {err}")
            finally:
                conn.close()

    # =============================== Member Management Functions ===============================
    def add_member(self):
        """Adds a new member to the database."""
        member_type = self.member_type_var.get()
        member_id = self.member_id_var.get()
        firstname = self.firstname_var.get()
        lastname = self.lastname_var.get()
        address = self.address_var.get()
        mobile = self.mobile_var.get()

        if not member_id or not firstname or not lastname:
            messagebox.showerror("Error", "Member ID, First Name, and Last Name are required to add a member.")
            return

        conn = self.Connect()
        if conn:
            try:
                my_cursor = conn.cursor()
                # Check if member ID already exists
                my_cursor.execute("SELECT ID FROM members WHERE ID = %s", (member_id,))
                if my_cursor.fetchone():
                    messagebox.showerror("Error", "Member with this ID already exists.")
                    return

                my_cursor.execute("""
                    INSERT INTO members (Member, ID, FirstName, LastNme, Address1, Mobile)
                    VALUES (%s, %s, %s, %s, %s, %s)
                """, (member_type, member_id, firstname, lastname, address, mobile))
                conn.commit()

                # Get the auto-generated PRN_NO
                my_cursor.execute("SELECT LAST_INSERT_ID()")
                last_prn = my_cursor.fetchone()[0]
                self.prn_var.set(last_prn) # Internally set the PRN No.

                messagebox.showinfo("Success", f"Member '{firstname} {lastname}' added successfully with PRN: {last_prn}")
                self.fetch_members() # Refresh the member table
                self.reset() # Clear form after adding
            except mysql.connector.Error as err:
                messagebox.showerror("Database Error", f"Error adding member: {err}")
            except Exception as e:
                messagebox.showerror("Error", f"An unexpected error occurred: {e}")
            finally:
                conn.close()

