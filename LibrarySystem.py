    def on_action_tab_change(self, event):
        """Switches the information tab based on the selected action tab."""
        selected_tab_id = self.buttons_notebook.select()
        selected_tab_text = self.buttons_notebook.tab(selected_tab_id, "text")

        if selected_tab_text == "Member Actions":
            self.notebook.select(1)  # Selects the "Member Records" tab (index 1)
        elif selected_tab_text == "Borrowing Actions":
            self.notebook.select(0)  # Selects the "Borrowed Records" tab (index 0)
        elif selected_tab_text == "Book Inventory Actions":
            # There isn't a direct "Book Inventory Records" tab,
            # so you might choose to keep it on Borrowed Records or leave as is.
            # For this example, let's keep it on Borrowed Records (index 0)
            self.notebook.select(0)
            messagebox.showinfo("Note", "Book Inventory Actions are primarily for adding new books, "
                                        "and available books are shown in the listbox above.")


